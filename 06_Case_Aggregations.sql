4.CASE STATEMENT!!!!

Query 1: Categorize employees based on salary
SELECT
    EMPLOYEE_ID,
    FIRST_NAME,
    SALARY,
    CASE
        WHEN SALARY >= 15000 THEN 'HIGH SALARY'
        WHEN SALARY >= 8000 THEN 'MEDIUM SALARY'
        ELSE 'LOW SALARY'
    END AS SALARY_CATEGORY
FROM EMPLOYEES
ORDER BY SALARY DESC;

Query 2: Categorize employees based on salary eligibility
SELECT
    EMPLOYEE_ID,
    FIRST_NAME,
    DEPARTMENT_ID,
    SALARY,
    CASE
        WHEN SALARY >= 12000 THEN 'BONUS ELIGIBLE'
        WHEN SALARY >= 8000 THEN 'REVIEW REQUIRED'
        ELSE 'NOT ELIGIBLE'
    END AS BONUS_STATUS
FROM EMPLOYEES;





5.AGGERGATE FUNCTIONS!!!!

Query 1: Department-wise salary analysis
SELECT
    DEPARTMENT_ID,
    COUNT(*) AS TOTAL_EMPLOYEES,
    SUM(SALARY) AS TOTAL_SALARY,
    AVG(SALARY) AS AVG_SALARY,
    MIN(SALARY) AS MIN_SALARY,
    MAX(SALARY) AS MAX_SALARY
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY TOTAL_SALARY DESC;

Query 2: Find departments having more than 5 employees
SELECT
    D.DEPARTMENT_NAME,
    COUNT(E.EMPLOYEE_ID) AS TOTAL_EMPLOYEES,
    AVG(E.SALARY) AS AVG_SALARY
FROM DEPARTMENTS D
JOIN EMPLOYEES E
    ON D.DEPARTMENT_ID = E.DEPARTMENT_ID
GROUP BY D.DEPARTMENT_NAME
HAVING COUNT(E.EMPLOYEE_ID) > 5
ORDER BY TOTAL_EMPLOYEES DESC;
