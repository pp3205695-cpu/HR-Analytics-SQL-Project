Query 1: Employee details with department and job title
SELECT
    E.EMPLOYEE_ID,
    E.FIRST_NAME,
    E.LAST_NAME,
    E.SALARY,
    D.DEPARTMENT_NAME,
    J.JOB_TITLE
FROM EMPLOYEES E
LEFT JOIN DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN JOBS J
    ON E.JOB_ID = J.JOB_ID;



Query 2: Employee location and country details
    SELECT
    E.EMPLOYEE_ID,
    E.FIRST_NAME,
    D.DEPARTMENT_NAME,
    L.CITY,
    C.COUNTRY_NAME
FROM EMPLOYEES E
LEFT JOIN DEPARTMENTS D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
LEFT JOIN LOCATIONS L
    ON D.LOCATION_ID = L.LOCATION_ID
LEFT JOIN COUNTRIES C
    ON L.COUNTRY_ID = C.COUNTRY_ID;
