Query 1: Find employees earning more than ₹10,000
    WITH HIGH_SALARY AS (
    SELECT
        EMPLOYEE_ID,
        FIRST_NAME,
        DEPARTMENT_ID,
        SALARY
    FROM EMPLOYEES
    WHERE SALARY > 10000
)
SELECT *
FROM HIGH_SALARY
ORDER BY SALARY DESC;

Query 2: Find employees earning above their department's average salary
WITH DEPT_AVG AS (
    SELECT
        DEPARTMENT_ID,
        AVG(SALARY) AS AVG_SALARY
    FROM EMPLOYEES
    GROUP BY DEPARTMENT_ID
)
SELECT
    E.EMPLOYEE_ID,
    E.FIRST_NAME,
    E.SALARY,
    D.AVG_SALARY,
    E.DEPARTMENT_ID
FROM EMPLOYEES E
JOIN DEPT_AVG D
    ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
WHERE E.SALARY > D.AVG_SALARY
ORDER BY E.SALARY DESC;
